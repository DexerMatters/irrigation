//! Immutable snapshots and View schemas.
//!
//! A snapshot captures the immutable content of every registered View at one
//! revision. Later revisions replace content values; they never mutate the
//! `Arc` a snapshot holds, so a retained snapshot keeps reading revision `r`
//! while the runtime advances.

use std::any::Any;
use std::sync::Arc;

use irrigation_core::descriptor::ViewDescriptor;
use irrigation_core::hash::FxHashMap;
use irrigation_core::ids::{Revision, Version, ViewId};

/// A schema-declared View over stock collection fields.
///
/// The marker is implemented by `#[incremental_data]`; indexes and projections
/// remain ordinary components over the generated handles.
pub trait IncrementalData: ViewSchema {}

/// A registered View type.
///
/// Generated by `#[view]`. The live handle is a zero-sized value; reads go
/// through the ambient computation frame. Snapshot handles borrow immutable
/// content and are not tracked.
pub trait ViewSchema: Sized + 'static {
    /// The View's static descriptor.
    const DESCRIPTOR: &'static ViewDescriptor;

    /// The immutable content type.
    type Content: Any + Send + Sync;

    /// The read-only handle produced by a snapshot.
    type Snapshot<'a>;

    /// The View identity.
    #[must_use]
    fn view_id() -> ViewId {
        Self::DESCRIPTOR.id
    }

    /// Wraps immutable content for snapshot reads.
    fn snapshot<'a>(content: &'a Arc<dyn Any + Send + Sync>) -> Self::Snapshot<'a>;
}

/// A View whose state is populated by edit transactions.
pub trait SourceView: ViewSchema {}

/// A View whose state is populated by component definitions.
pub trait DerivedView: ViewSchema {}

/// A View that can be edited through a transaction.
pub trait EditableView: ViewSchema {
    /// The editor handle produced by `edit.view::<V>()`.
    type Editor<'a>;

    /// Builds an editor borrowing the transaction.
    fn edit<'a>(edit: &'a mut crate::edit::Edit) -> Self::Editor<'a>;
}

/// What changed between two notifications of one observation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ChangeSummary {
    /// The observed View.
    pub view: ViewId,
    /// Content version before the change.
    ///
    /// This is the View's *content* version, not a unit version. A subscription
    /// that watches units instead of the whole View is woken by a per-unit move
    /// that does not advance the content -- a host edit to one source unit, or a
    /// provider handover -- so for those notifications `previous == current`.
    /// Do not read the inequality as "something changed": the wake is the event.
    pub previous: Version,
    /// Content version now: see [`Self::previous`] for when it equals it.
    pub current: Version,
    /// How many watched units moved for this wake.
    ///
    /// Zero for a whole-View subscription, which watches the content. For a unit
    /// subscription this is the only field that is non-zero when the versions above
    /// are equal, which is the normal case: a per-unit move does not advance the
    /// View's content.
    pub moved: u32,
}

/// Immutable content captured at one revision.
pub struct Snapshot {
    revision: Revision,
    views: FxHashMap<ViewId, Arc<dyn Any + Send + Sync>>,
    versions: FxHashMap<ViewId, Version>,
    routing: FxHashMap<ViewId, u64>,
}

impl std::fmt::Debug for Snapshot {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Snapshot")
            .field("revision", &self.revision)
            .field("views", &self.views.len())
            .finish()
    }
}

impl Snapshot {
    pub(crate) fn new(
        revision: Revision,
        views: FxHashMap<ViewId, Arc<dyn Any + Send + Sync>>,
        versions: FxHashMap<ViewId, Version>,
        routing: FxHashMap<ViewId, u64>,
    ) -> Self {
        Self {
            revision,
            views,
            versions,
            routing,
        }
    }

    /// The routing certificate this snapshot observed for one View.
    #[must_use]
    pub fn routing_stamp(&self, view: ViewId) -> Option<crate::runtime::RoutingStamp> {
        self.routing
            .get(&view)
            .map(|version| crate::runtime::RoutingStamp {
                view,
                version: *version,
            })
    }

    /// The revision this snapshot observes.
    #[must_use]
    pub fn revision(&self) -> Revision {
        self.revision
    }

    /// Returns a read-only handle for a View.
    ///
    /// # Panics
    ///
    /// Panics when the View was never registered on this runtime.
    #[must_use]
    pub fn view<V: ViewSchema>(&self) -> V::Snapshot<'_> {
        let content = self
            .views
            .get(&V::view_id())
            .unwrap_or_else(|| panic!("view `{}` is not registered", V::DESCRIPTOR.name));
        V::snapshot(content)
    }

    /// Returns the revision at which a View's content last changed.
    #[must_use]
    pub fn version<V: ViewSchema>(&self) -> Option<Version> {
        self.versions.get(&V::view_id()).copied()
    }

    /// Returns the content version for a raw View identity, or zero when the
    /// View was never captured.
    #[must_use]
    pub(crate) fn version_of(&self, view: ViewId) -> Version {
        self.versions.get(&view).copied().unwrap_or(0)
    }

    /// Returns `true` when the snapshot contains the View.
    #[must_use]
    pub fn contains<V: ViewSchema>(&self) -> bool {
        self.views.contains_key(&V::view_id())
    }
}
